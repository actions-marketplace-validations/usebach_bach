# Turns bench\results\*.json into Markdown tables (bench\RESULTS.md).
#
#   powershell -ExecutionPolicy Bypass -File bench\summarize.ps1

$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$files = Get-ChildItem (Join-Path $here 'results') -Filter '*.json' | Sort-Object Name
$order = 'bach', 'inno', 'nsis', 'wix'
$data = @{}
foreach ($f in $files) { $d = Get-Content $f.FullName -Raw | ConvertFrom-Json; $data[$d.tool] = $d }
$tools = @($order | Where-Object { $data.ContainsKey($_) })
$label = @{ bach = 'Bach'; inno = 'Inno Setup'; nsis = 'NSIS'; wix = 'WiX (MSI)' }

function Median($values) {
    $v = @($values | Where-Object { $null -ne $_ } | Sort-Object)
    if ($v.Count -eq 0) { return $null }
    $v[[int][math]::Floor(($v.Count - 1) / 2)]
}
function Num($x, $unit) { if ($null -eq $x) { 'n/a' } else { "$x$unit" } }

$sb = New-Object Text.StringBuilder
function Line($text = '') { [void]$sb.AppendLine($text) }

Line '# Installer comparison: results'
Line
Line 'Generated by `bench\summarize.ps1` from `bench\results\*.json`. See `bench\README.md` for how the numbers were made and what they do and do not say.'
Line
Line '## Building (355 MB, 10,107 files)'
Line
Line '| Tool | Settings | Build time | Setup file | Peak memory |'
Line '| --- | --- | ---: | ---: | ---: |'
foreach ($t in $tools) {
    $d = $data[$t]
    foreach ($p in $d.build.PSObject.Properties) {
        if ($p.Name -eq 'v1_1_0') { continue }
        $b = $p.Value
        Line ("| {0} | {1} | {2} | {3} | {4} |" -f $label[$t], $p.Name, (Num $b.seconds ' s'), (Num $b.size_mb ' MB'), (Num $b.peak_mb ' MB'))
    }
}
Line
Line '## Installing, updating and removing (the tool''s default build)'
Line
Line '| Tool | Install (median of runs) | Update 1.0.0 to 1.1.0 | Remove | Install correct | Old files left after update |'
Line '| --- | ---: | ---: | ---: | :---: | ---: |'
foreach ($t in $tools) {
    $d = $data[$t]
    $ins = Median ($d.install | ForEach-Object { $_.seconds })
    # Removal is done when the folder and the entry are gone: the time the uninstaller ran
    # plus the time it took afterwards (an uninstaller that hands over to a copy returns at once).
    $rem = Median ($d.uninstall | ForEach-Object { if ($null -ne $_.until_gone_seconds) { [math]::Round($_.seconds + $_.until_gone_seconds, 1) } })
    $ok = $(if ($d.verify.Identical) { 'yes' } else { 'no' })
    Line ("| {0} | {1} | {2} | {3} | {4} | {5} |" -f $label[$t], (Num $ins ' s'), (Num $d.update.seconds ' s'), (Num $rem ' s'), $ok, $d.update.stale_files)
}
Line
Line '## What an installer adds to a tiny app'
Line
Line '| Tool | Setup file | App | Added by the installer |'
Line '| --- | ---: | ---: | ---: |'
foreach ($t in $tools) { $x = $data[$t].tiny; Line ("| {0} | {1} KB | {2} KB | {3} KB |" -f $label[$t], $x.installer_kb, $x.app_kb, $x.overhead_kb) }
Line
Line '## When things go wrong'
Line
Line '| Tool | Locked file during an update | Damaged installer (1 byte flipped) | Killed half way, then run again | User files after removal |'
Line '| --- | --- | --- | --- | --- |'
foreach ($t in $tools) {
    $d = $data[$t]
    $locked = "$($d.locked_update.state) (exit $($d.locked_update.exit)$(if ($d.locked_update.timed_out) { ', hung' }))"
    $dmg = $(if ($d.damaged.refused) { "refused, nothing written (exit $($d.damaged.exit))" } else { "exit $($d.damaged.exit), $($d.damaged.files_written) files written$(if ($d.damaged.entry_written) { ', entry in Settings' })" })
    $kill = $(if ($null -eq $d.killed) { 'not tested' } else { "left $($d.killed.files_when_killed) of $($d.killed.of) files; second run exit $($d.killed.rerun_exit), $(if ($d.killed.rerun_identical) { 'correct' } else { 'not correct' })" })
    $user = $(if ($d.user_files.kept_after_removal) { 'kept' } else { 'deleted' })
    Line ("| {0} | {1} | {2} | {3} | {4} |" -f $label[$t], $locked, $dmg, $kill, $user)
}
Line
Line '## What was left behind after a removal'
Line
foreach ($t in $tools) {
    $left = @($data[$t].leftovers_after_remove)
    Line ("- **{0}**: {1}" -f $label[$t], $(if ($left.Count -eq 0) { 'nothing' } else { ($left -join '; ') }))
}
Set-Content -Encoding UTF8 (Join-Path $here 'RESULTS.md') $sb.ToString()
Write-Host 'wrote bench\RESULTS.md'
